(() => {
  'use strict';

  // Chromium 131+ renders CSS page-margin boxes when printing from the browser.
  // Other print engines may ignore these boxes; report content remains usable.
  const STYLE_ID = 'mgs-report-page-rules';
  const MAX_IDENTIFIER_LENGTH = 65;

  function compact(value) {
    return String(value ?? '').replace(/[\u0000-\u001f\u007f]+/g, ' ').replace(/\s+/g, ' ').trim();
  }

  function projectHeader(project) {
    if (!project) return 'MGS | No project selected';
    const name = compact(project.name || 'Unnamed project');
    const number = compact(project.handoffMetadata?.projectNumber).slice(0, 24);
    const identifier = (number ? `${number} | ${name}` : name).slice(0, MAX_IDENTIFIER_LENGTH);
    return `MGS | ${identifier}`;
  }

  function cssQuoted(value) {
    return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
  }

  function update(project) {
    let style = document.getElementById(STYLE_ID);
    if (!style) {
      style = document.createElement('style');
      style.id = STYLE_ID;
      document.head.appendChild(style);
    }
    // @page margin boxes repeat on every physical sheet, including continuation
    // pages; CSS counters are generated by the print engine, not stored in data.
    style.textContent = `@media print {
      @page {
        size: Letter;
        margin: .77in .55in .72in;
        @top-left {
          content: ${cssQuoted(projectHeader(project))};
          color: #485363;
          font: 8pt Arial, sans-serif;
        }
        @bottom-right {
          content: "Page " counter(page) " of " counter(pages);
          color: #485363;
          font: 8pt Arial, sans-serif;
        }
      }
    }`;
  }

  window.MGSReportPrint = Object.freeze({ update, projectHeader });
})();
